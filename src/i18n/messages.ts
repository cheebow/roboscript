const DICTIONARIES: Record<Language, Record<MessageKey, string>> = { en, ja };

/** The text for the key in the current language, with each {name} replaced by the parameter of that name. */
export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  const text = DICTIONARIES[currentLanguage()][key];
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}
