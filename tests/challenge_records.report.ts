import { writeFileSync } from 'node:fs';
import { describe, it } from 'vitest';
import { CHALLENGES, challengeLoadout, playChallenge } from '../src/challenge';
import { RECORD_PROGRAM_KEYS, programSource, type ChallengeRecord, type ChallengeRecordSample, type ChallengeRecords } from '../src/challenge/records';
import { teamCostLimitFor } from '../src/data/castle';
import { COST_LIMIT, PARTS, STANDARD_LOADOUT, costOf, type Loadout } from '../src/data/parts';
import { RULES_VERSION } from '../src/data/rules_version';
import { TEMPLATES } from '../src/data/templates';

// `npm run records`: plays every challenge with a pool of known programs and parts,
// and writes the cleared tries to src/data/challenge_records.ts, bundled with the
// game as the reference records a player's clear is shown among. Run it again after
// a change to the rules, the challenges or the programs (the tests say when).

const OUT = 'src/data/challenge_records.ts';

/** The parts every program is tried with: standard, every single swap, and a few staples. */
function loadoutPool(): Loadout[] {
  const pool: Loadout[] = [{ ...STANDARD_LOADOUT }];
  for (const part of PARTS) {
    if (part.id === 'standard') continue;
    pool.push({ ...STANDARD_LOADOUT, [part.slot]: part.id });
  }
  const staples: Partial<Loadout>[] = [
    { gun: 'cannon', sensor: 'scope' },
    { gun: 'cannon', body: 'light' },
    { gun: 'rapid', sensor: 'short' },
    { body: 'heavy', sensor: 'short' },
    { body: 'light', legs: 'sprint' },
    { legs: 'sprint', sensor: 'scope' },
  ];
  for (const staple of staples) pool.push({ ...STANDARD_LOADOUT, ...staple });
  return pool;
}

describe('challenge records', () => {
  it('measures every challenge and writes the bundled records', () => {
    const pool = loadoutPool();
    const keys = [...RECORD_PROGRAM_KEYS, ...TEMPLATES.map((template) => template.id)];
    const challenges: Record<string, ChallengeRecord> = {};

    for (const challenge of CHALLENGES) {
      const seen = new Set<string>();
      const cleared: ChallengeRecordSample[] = [];
      let tried = 0;

      for (const key of keys) {
        const source = programSource(key, challenge);
        if (source === null) throw new Error(`no program behind ${key}`);
        const chosens = key === 'answer' ? [{ ...STANDARD_LOADOUT, ...challenge.answerParts }, ...pool] : pool;
        for (const chosen of chosens) {
          // As the screen would play it: the challenge's fixed parts over the chosen ones.
          const loadout = challengeLoadout(challenge, chosen);
          const size = challenge.stage.teamSize;
          if (size === undefined ? costOf(loadout) > COST_LIMIT : costOf(loadout) * size > teamCostLimitFor(size)) continue;
          const once = `${key} ${loadout.body} ${loadout.legs} ${loadout.gun} ${loadout.sensor}`;
          if (seen.has(once)) continue;
          seen.add(once);
          tried += 1;
          const result = playChallenge(challenge, source, loadout);
          if ('errors' in result) continue;
          if (result.cleared) cleared.push({ program: key, loadout, seconds: result.record.seconds });
        }
      }

      cleared.sort((a, b) => a.seconds - b.seconds);
      const seconds = cleared.map((each) => each.seconds);
      const picks = cleared.length === 0 ? [] : [cleared[0], cleared[Math.floor(cleared.length / 2)], cleared[cleared.length - 1]];
      challenges[challenge.id] = { seconds, samples: picks, tried };
      const spread = seconds.length === 0 ? 'none cleared' : `${seconds[0].toFixed(1)}s .. ${seconds[seconds.length - 1].toFixed(1)}s`;
      console.log(`${challenge.id}: ${seconds.length}/${tried} cleared, ${spread}`);
    }

    const records: ChallengeRecords = { rulesVersion: RULES_VERSION, challenges };
    const header =
      '// Generated by `npm run records` (tests/challenge_records.report.ts): the cleared\n' +
      '// reference tries of every challenge, measured by playing them. Do not edit by hand.\n\n';
    const body = `import type { ChallengeRecords } from '../challenge/records';\n\nexport const CHALLENGE_RECORDS: ChallengeRecords = ${JSON.stringify(records, null, 2)};\n`;
    writeFileSync(OUT, header + body);
    console.log(`written to ${OUT}`);
  }, 0);
});
